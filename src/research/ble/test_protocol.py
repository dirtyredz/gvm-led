"""Plain unittest checks for protocol.py.

Run from anywhere: python -m unittest discover -s <repo>/src/research/ble
Vectors come from docs/research/protocol.md (not generated by the code under test).
"""
import unittest

import protocol as p

HELLO = bytes.fromhex("4C5409000053000001009474FF")
HELLO_REPLY = bytes.fromhex("4C540A003353000002203 8F39B".replace(" ", ""))


class ProtocolTest(unittest.TestCase):
    def test_hello_crc_and_frame(self):
        self.assertEqual(p.crc16_xmodem(bytes.fromhex("4C540900005300000100")), 0x9474)
        self.assertEqual(p.hello_packet(True), HELLO)
        self.assertEqual(p.hello_packet(False), HELLO[:-1])

    def test_hello_reply_parses(self):
        frames = p.FrameDecoder().feed(HELLO_REPLY)
        self.assertEqual(len(frames), 1)
        h = p.parse_hello(frames[0])
        self.assertEqual((h.devid, h.devtype, h.cct_min, h.cct_max), (0, 0x33, 3200, 5600))

    def test_rejects_bad_crc_and_resyncs(self):
        bad = bytearray(HELLO_REPLY)
        bad[-1] ^= 0x01
        dec = p.FrameDecoder()
        self.assertEqual(dec.feed(bytes(bad)), [])
        self.assertEqual(len(dec.rejected), 1)
        self.assertEqual(len(dec.feed(HELLO_REPLY)), 1)

    def test_fragmented_and_coalesced(self):
        dec = p.FrameDecoder()
        self.assertEqual(dec.feed(HELLO_REPLY[:5]), [])
        self.assertEqual(len(dec.feed(HELLO_REPLY[5:] + b"\xff" + HELLO_REPLY)), 2)

    def test_set_packet_framing(self):
        # protocol.md: brightness 50 % = 4C 54 09 00 33 57 00 02 01 32 CRC
        pkt = p.set_packet(0, 0x33, p.C_BRIGHT, 50, ff=False)
        self.assertEqual(pkt[:10], bytes.fromhex("4C54090033570002013 2".replace(" ", "")))
        self.assertEqual(pkt[2], len(pkt) - 3)
        fr = p.FrameDecoder().feed(pkt)[0]
        self.assertEqual((fr.kind, fr.payload), (0x57, bytes([0, 2, 1, 50])))

    def test_state_decode_and_compare(self):
        d = p.decode_state(bytes([1, 11, 50, 44, 0, 100, 2, 0, 0]))
        self.assertEqual((d["power"], d["bright"], d["mode"], d["hue"], d["sat"]), (1, 50, 2, 0, 100))
        self.assertEqual(p.compare_state(dict(mode=2, hue=0, sat=100, bright=50), d), [])
        self.assertEqual(p.compare_state(dict(mode=2, cct=3200), d), [])  # cct does not apply to HSI
        self.assertEqual(len(p.compare_state(dict(mode=2, hue=60), d)), 1)
        self.assertEqual(p.compare_state(dict(power=1), None), ["no report"])
        short = p.decode_state(bytes([1, 11, 50, 44]))
        self.assertEqual(len(p.compare_state(dict(mode=2, hue=0), short)), 2)

    def test_ack_echoes_payload(self):
        payload = bytes([1, 11, 50, 44, 0, 100, 2, 0, 0])
        fr = p.FrameDecoder().feed(p.ack_packet(0, 0x33, payload))[0]
        self.assertEqual((fr.kind, fr.payload), (0x48, payload))


if __name__ == "__main__":
    unittest.main()
